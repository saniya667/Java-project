package javapackage;

public class Datatypepgm {

	public static void main(String[] args) {
		byte byteNumber=10;
		System.out.println("The value of byteNumber="+byteNumber);
		short shortNumber=15;
		System.out.println("The value of shortnumber="+shortNumber);
		int intNumber=56;
		System.out.println("The value of intnumber="+intNumber);
		long  longNumber=88888888887765444L;
		System.out.println("The value of longNumber="+longNumber);
		float floatNumber=31.67F;
		System.out.println("The value of floatnumber="+floatNumber);
		double doubleNumber=8.90;
		System.out.println("The value of doublenumber="+doubleNumber);
		boolean result=5>3;
		System.out.println("The value of result="+result);
		char characterValue='H';//char value should be enclosed in single quotes.
		System.out.println("The value of charValue="+characterValue);
		char symbol='&';
		System.out.println("The value of symbol= "+symbol);
		String name="saniya";//string value should be enclosed in double quotes.
		System.out.println("The value of string="+name);
	}

}
